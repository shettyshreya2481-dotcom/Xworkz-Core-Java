class Capacitor{
private String capacitorId;
private String capacitorCapacity;

public void setCapacitorId(String capacitorId){
this.capacitorId=capacitorId;
}

public String  getCapacitorId(){
return capacitorId;
}

public void setCapacitorCapacity(String capacitorCapacity){
	this.capacitorCapacity=capacitorCapacity;
}

public String getCapacitorCapacity(){
	return capacitorCapacity;
}



}